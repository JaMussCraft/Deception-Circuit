#!/usr/bin/env python3
"""
p1_results.py -- the combined phase-1 results of ticket 03 (reports/03-phase1-results.md + .json).

Links the three block reports rather than duplicating them (orchestrator, 2026-10-25) and carries the headline numbers
of each block into one JSON: 1A R-A1 per set (reports/03-1a-results.json), 1B class counts and pre-registered checks
(03-1b-results.json), 1C readings, R-inv, routing and the U-only arm (03-1c-results.json).

usage: python outputs/_launch_mechanism_analysis/p1_results.py [--reports DIR]
"""

from __future__ import annotations

import argparse
import json
import os
import sys

REPORTS = "/projects/beto/swong2/Alignment/.scratch/mechanism-analysis/reports"


def _load(p):
    with open(p) as f:
        return json.load(f)


def combine(a1, b1, c1) -> dict:
    ra1 = {f"{r['task']}/set{r['set']}": r["ra1"] for r in a1["sets"] if r.get("ra1")}
    rab = {t: {"reading": r["reading"], "deciding": r["deciding"],
               **{k: r["candidates"][r["deciding"]][k] for k in ("k", "f", "f_ci", "acc", "null_f_max", "i", "ii")}}
           for t, r in c1["rab"].items()}
    rinv = {t: {row: (v.get(key) or {}).get("label") for row, key in
                (("optionB", "all"), ("optionB_inversion_polarity", "inversion_polarity"), ("r19", "r19"))}
            for t, v in c1["rinv"].items()}
    uonly = {t: {c["k"]: c["f"] for c in r["candidates"].values() if c["selector"] == "uonly"}
             for t, r in c1["rab"].items()}
    return {"generated_by": "outputs/_launch_mechanism_analysis/p1_results.py",
            "sources": {"1a": "03-1a-results.json", "1b": "03-1b-results.json", "1c": "03-1c-results.json"},
            "ra1": ra1, "class_counts": b1["class_counts"], "rqa": b1["rqa"], "positive_control": b1["positive_control"],
            "c_own": {t: {k: v.get(k) for k in ("k", "n", "p", "p_holm", "holds")} for t, v in b1["c_own"].items()},
            "c_mlp_holds": (b1.get("c_mlp") or {}).get("holds"), "c_v1_holds": (b1.get("c_v1") or {}).get("holds"),
            "lens_contrasts": {k: {"diff": v["diff"], "ci": v["ci"]} for k, v in b1["lens"]["contrasts"].items()},
            "rab_overall": c1["overall"], "rab": rab, "rinv": rinv, "routing": c1["routing"], "uonly_f": uonly,
            "c_confound": c1["c_confound"]["text"]}


def markdown(res) -> str:
    L = ["# Ticket 03 phase-1 results (combined)", "",
         "Generated by `outputs/_launch_mechanism_analysis/p1_results.py`. The full tables live in the block reports:",
         "", "- 1A, mean / zero / interchange circuit knockouts and R-A1: [03-1a-results.md](03-1a-results.md)",
         "- 1B, mask-independent sweeps, R-cls, C1, C-own, C-MLP, C-v1, R-lens: [03-1b-results.md](03-1b-results.md)",
         "- 1C, R-AB, R-inv, routing, S7 vs S2p, the U-only arm, C-confound: [03-1c-results.md](03-1c-results.md)",
         "- Reading: [03-phase1-reading.md](03-phase1-reading.md)", "", "## Headline numbers", "",
         "| task | R-AB | deciding set | f_D [95% CI] | KO acc | null f max | (i) | (ii) | R-inv option B | inversion-polarity | R19(3) subset |",
         "| --- " * 11 + "|"]
    for t, r in res["rab"].items():
        v = res["rinv"][t]
        L.append(f"| {t} | {r['reading']} | {r['deciding']} | {r['f']:.3f} [{r['f_ci'][0]:.3f}, {r['f_ci'][1]:.3f}] | "
                 f"{r['acc']:.3f} | {r['null_f_max']:.3f} | {'yes' if r['i'] else 'no'} | {'yes' if r['ii'] else 'no'} | "
                 f"{v['optionB']} | {v['optionB_inversion_polarity']} | {v['r19']} |")
    L += ["", f"R-AB overall: **{res['rab_overall']}**.", "", "| task | set 3 core | set 4 excl | set 5 D-H | set 6 (D-H)-core |",
          "| --- | --- | --- | --- | --- |"]
    for t in ("far", "sdr", "ser"):
        L.append(f"| {t} | " + " | ".join(res["ra1"].get(f"{t}/set{s}", "-") for s in (3, 4, 5, 6)) + " |")
    L += ["", "R-A1 under the pre-registered columns (mean D-test accuracy, zero no-pressure rate).", "",
          f"Pre-registered checks: C-own holds on {sum(bool(v['holds']) for v in res['c_own'].values())} of 3 tasks; "
          f"C-MLP holds: {res['c_mlp_holds']}; C-v1 holds: {res['c_v1_holds']}. C-confound: {res['c_confound']}", ""]
    return "\n".join(L)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--reports", default=REPORTS)
    a = p.parse_args(argv)
    res = combine(*(_load(os.path.join(a.reports, f"03-{b}-results.json")) for b in ("1a", "1b", "1c")))
    with open(os.path.join(a.reports, "03-phase1-results.json"), "w") as f:
        json.dump(res, f, indent=1)
    with open(os.path.join(a.reports, "03-phase1-results.md"), "w") as f:
        f.write(markdown(res))
    print(f"wrote {a.reports}/03-phase1-results.{{md,json}}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
