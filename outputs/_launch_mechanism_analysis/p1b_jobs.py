#!/usr/bin/env python3
"""
p1b_jobs.py -- the phase-1B job files of the mechanism-analysis feature (ticket 03, spec section 4, R11, R16).

Writes one `analyze_components.py batch` file per task under docs/research/mechanism-analysis/jobs/:

    03-p1b-<t>.batch      S1 S2 S2p S3 S4 S5 S6 on the selection sample (n = 100, seed 0), then L (DLA + lens)

Every line binds U = (Df|Hf|Ds|Hs|De|He) - m at leaf (the 123-head union of the six coarse v2 circuits minus the
all-MLP operand; heads at head granularity would leak every MLP, memory dh-core-component-analysis) and the six
atomic runs as references, exactly as ticket 02a's dry-run driver and smoke job did. Test sets come from
--task-from: D and H their own runs, F the tracked nopressure stand-in. Each cell writes its own output dir
outputs/_analyses/mechanism-analysis-p1/<cell>/U__leaf/<test set>/, so the three task jobs never share a cell dir.

| cell | test set | counterfactual / scheme | positions |
| S1   | D | item-swap                      | all |
| S2   | D | neutral twin                   | all |
| S2p  | D | neutral twin, mlp.0.0 excluded  | after=pressure_clause,exclude=readout |
| S3   | D | neutral twin                   | readout |
| S4   | D | mean (bank over D's split)      | all |
| S5   | H | item-swap (honest margin)       | all |
| S6   | F | item-swap (honest margin)       | all |
| L    | D (pressure + neutral twin, 1,000 rows), F (pressure) | DLA + logit lens with crossing summary |

usage (from the repository root):
    python outputs/_launch_mechanism_analysis/p1b_jobs.py [--out-root DIR] [--jobs-dir DIR]
"""

from __future__ import annotations

import argparse
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))

RUNS = {
    "far": ("outputs/llama-8b-instruct_far_v2_coarse/nls0.3_noedge_noan_nomh_nomo_nomb_261021-140717",
            "outputs/llama-8b-instruct_far_v2_coarse/nls0.3_honest_noedge_noan_nomh_nomo_nomb_261021-140323"),
    "sdr": ("outputs/llama-8b-instruct_sdr_v2_coarse/nls0.3_noedge_noan_nomh_nomo_nomb_261021-140323",
            "outputs/llama-8b-instruct_sdr_v2_coarse/nls0.3_honest_noedge_noan_nomh_nomo_nomb_261021-140323"),
    "ser": ("outputs/llama-8b-instruct_ser_v2_coarse/nls0.3_noedge_noan_nomh_nomo_nomb_261021-173101",
            "outputs/llama-8b-instruct_ser_v2_coarse/nls0.3_honest_noedge_noan_nomh_nomo_nomb_261021-140323"),
}
SHORT = {"far": "f", "sdr": "s", "ser": "e"}
ALLMLP = "outputs/_launch_mechanism_v2/evals/operands/allmlp_nomb_v2"
STANDIN_F = "outputs/_launch_mechanism_v2/evals/standins/{t}_v2_nopressure"
POST = "after=pressure_clause,exclude=readout"
OUT_ROOT = "outputs/_analyses/mechanism-analysis-p1"
JOBS_DIR = "docs/research/mechanism-analysis/jobs"


def binding() -> list:
    """U at leaf plus the six atomic runs as references (02a's smoke binding)."""
    out = []
    for t, (d, h) in RUNS.items():
        out += ["--circuit", f"D{SHORT[t]}={d}", "--circuit", f"H{SHORT[t]}={h}"]
    out += ["--circuit", f"m={ALLMLP}", "--expr", "U=(Df|Hf|Ds|Hs|De|He)-m", "--compose-granularity", "leaf"]
    for t, (d, h) in RUNS.items():
        out += ["--reference", f"{t}_D={d}", "--reference", f"{t}_H={h}"]
    return out


def cells(t: str, out_root: str = OUT_ROOT) -> list:
    """[(cell, argv)] for one task, in run order."""
    d, h = RUNS[t]
    f = STANDIN_F.format(t=t)
    sweep = ["--analyses", "knockout", "--knockout-completeness-sweep"]
    twin = ["--knockout-counterfactual", "neutral_twin"]

    def out(cell):
        return ["--output-dir", f"{out_root}/{cell}"]
    return [
        ("s1", ["--task-from", d] + sweep + out("s1")),
        ("s2", ["--task-from", d] + sweep + twin + out("s2")),
        ("s2p", ["--task-from", d] + sweep + twin + ["--knockout-positions", POST, "--knockout-sweep-exclude",
                                                     "mlp.0.0"] + out("s2p")),
        ("s3", ["--task-from", d] + sweep + twin + ["--knockout-positions", "readout"] + out("s3")),
        ("s4", ["--task-from", d] + sweep + ["--knockout-scheme", "mean"] + out("s4")),
        ("s5", ["--task-from", h] + sweep + out("s5")),
        ("s6", ["--task-from", f] + sweep + out("s6")),
        ("lens", ["--task-from", d, "--analyses", "dla", "--dla-conditions", "pressure,neutral_twin"] + out("lens")),
        ("lens_f", ["--task-from", f, "--analyses", "dla", "--dla-conditions", "pressure"] + out("lens_f")),
    ]


def batch_text(t: str, out_root: str = OUT_ROOT) -> str:
    head = [f"# Ticket 03 phase 1B, task {t}: seven sweeps and the lens cell on the selection sample (n = 100, seed 0),",
            "# U bound (the 123-head union of the six coarse v2 circuits minus m, at leaf), one model load.",
            f"# Generated by outputs/_launch_mechanism_analysis/p1b_jobs.py; do not edit by hand.",
            "# Run from the repo root:  python analyze_components.py batch <this file> "
            f"--timings {out_root}/timings/{t}.json",
            "# Login check:            python analyze_components.py batch <this file> --dry-run", ""]
    lines = []
    for cell, argv in cells(t, out_root):
        lines += [f"# {cell}", shlex.join(binding() + argv)]
    return "\n".join(head + lines) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--out-root", default=OUT_ROOT, help="cell output root written into the lines")
    p.add_argument("--jobs-dir", default=os.path.join(REPO, JOBS_DIR))
    a = p.parse_args(argv)
    os.makedirs(a.jobs_dir, exist_ok=True)
    for t in RUNS:
        path = os.path.join(a.jobs_dir, f"03-p1b-{t}.batch")
        with open(path, "w") as f:
            f.write(batch_text(t, a.out_root))
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
