#!/usr/bin/env python3
"""
p1c_jobs.py -- the phase-1C job files of the mechanism-analysis feature (ticket 03, spec sections 2.3, 2.4, 4; R11, R19).

Phase 1C runs in two waves, because both selectors rank from 1B's S2p sweep and the held-out groups need the greedy
selector's sets:

  wave a  (`a`)  per task, on the selection sample (n = 100, seed 0):
                 S7 = the neutral-twin sweep on I at post-clause positions, layer-0 MLP excluded (descriptive);
                 greedy joint selection over the S2p top 50 to k = 20 (pool read from 1B's S2p sweep.json on the
                 cluster, signed order).
  wave b  (later, from the groups files `p1c_groups.py` writes): the held-out tests.

It also writes the config-only I stand-ins (`standins/<t>_v2_inversion/config.json`): the committed nopressure
stand-in of ticket 06 with `deception_condition: inversion`, so `--task-from` loads `data/datasets/<t>_v2_inversion`
(ticket 08, c2d47da).

usage (from the repository root):
    python outputs/_launch_mechanism_analysis/p1c_jobs.py a [--out-root DIR] [--jobs-dir DIR]
"""

from __future__ import annotations

import argparse
import json
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)
import p1b_jobs as pb  # noqa: E402

REPO = pb.REPO
STANDIN_I = "outputs/_launch_mechanism_analysis/standins/{t}_v2_inversion"
POOL = "{root}/s2p/U__leaf/{t}_v2/knockout/sweep.json"
GREEDY_POOL_SIZE = 50
GREEDY_K_MAX = 20


def write_standins(repo: str = REPO) -> list:
    out = []
    for t in pb.RUNS:
        with open(os.path.join(repo, pb.STANDIN_F.format(t=t), "config.json")) as f:
            cfg = json.load(f)
        cfg["deception_condition"] = "inversion"
        d = os.path.join(repo, STANDIN_I.format(t=t))
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, "config.json")
        with open(path, "w") as f:
            json.dump(cfg, f, indent=1)
            f.write("\n")
        out.append(path)
    return out


def cells_a(t: str, out_root: str = pb.OUT_ROOT) -> list:
    d, _ = pb.RUNS[t]
    twin = ["--knockout-counterfactual", "neutral_twin", "--knockout-positions", pb.POST]
    return [
        ("s7", ["--task-from", STANDIN_I.format(t=t), "--analyses", "knockout", "--knockout-completeness-sweep"]
         + twin + ["--knockout-sweep-exclude", "mlp.0.0", "--output-dir", f"{out_root}/s7"]),
        ("greedy", ["--task-from", d, "--analyses", "knockout", "--knockout-singles", "off"] + twin
         + ["--knockout-greedy-pool", POOL.format(root=out_root, t=t),
            "--knockout-greedy-pool-size", str(GREEDY_POOL_SIZE), "--knockout-greedy-k-max", str(GREEDY_K_MAX),
            "--output-dir", f"{out_root}/greedy"]),
    ]


def batch_a(out_root: str = pb.OUT_ROOT) -> str:
    head = ["# Ticket 03 phase 1C wave a: per task, S7 (I, neutral twin, post-clause) and the greedy selector over the",
            "# S2p top 50 to k = 20, on the selection sample (n = 100, seed 0); U bound; one model load for all three.",
            "# Needs 1B's S2p sweep.json on the cluster (the greedy pool). Generated by "
            "outputs/_launch_mechanism_analysis/p1c_jobs.py.",
            f"# Run: python analyze_components.py batch <this file> --timings {out_root}/timings/1c-a.json", ""]
    lines = []
    for t in pb.RUNS:
        for cell, argv in cells_a(t, out_root):
            lines += [f"# {t} {cell}", shlex.join(pb.binding() + argv)]
    return "\n".join(head + lines) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("wave", choices=["a"])
    p.add_argument("--out-root", default=pb.OUT_ROOT)
    p.add_argument("--jobs-dir", default=os.path.join(REPO, pb.JOBS_DIR))
    a = p.parse_args(argv)
    for path in write_standins():
        print(path)
    os.makedirs(a.jobs_dir, exist_ok=True)
    path = os.path.join(a.jobs_dir, "03-p1c-a.batch")
    with open(path, "w") as f:
        f.write(batch_a(a.out_root))
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
