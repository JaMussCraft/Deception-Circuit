# worklog-append kinds


def _next_id(items, prefix):
    nums = [int(x["id"][len(prefix):]) for x in items if re.match(r"^%s[0-9]+$" % prefix, x.get("id", ""))]
    return "%s%d" % (prefix, (max(nums) + 1) if nums else 1)


def _need(args, *names):
    missing = ["--" + n.replace("_", "-") for n in names if getattr(args, n, None) in (None, "")]
    if missing:
        raise UsageError("--kind %s needs %s" % (args.kind, ", ".join(missing)))


def _compaction_title(st):
    n = compactions(st)
    if not n:
        raise UsageError("--kind compaction needs --title: state.json records no compaction yet")
    return "Resumed after compaction #%d" % n


def make_mutator(args, cfg, session=None):
    kind = args.kind

    def mutate(ctx):
        wl, t = ctx.wl, ctx.t
        if kind == "finding":
            _need(args, "plain", "setup", "strength", "evidence")
            if args.strength not in registry.STRENGTH:
                raise UsageError("--strength must be one of %s" % ", ".join(registry.STRENGTH))
            fid = _next_id(wl["findings"], "F")
            wl["findings"].append({"id": fid, "at": paths.iso(t), "plain": records.sentence(args.plain),
                                   "setup": records.sentence(args.setup), "strength": args.strength,
                                   "evidence": args.evidence.strip()})
            ctx.messages.append("recorded finding %s" % fid)
            return entry_text(t, args.title or "Finding %s recorded" % fid, args.body or records.sentence(args.plain))
        if kind == "need":
            _need(args, "text", "default")
            nid = _next_id(wl["needs"], "N")
            default = records.sentence(DEFAULT_PREFIX_RE.sub("", args.default.strip()))
            wl["needs"].append({"id": nid, "at": paths.iso(t), "text": records.sentence(args.text),
                                "default": default, "answer": None, "answered_at": None})
            ctx.messages.append("opened need %s" % nid)
            return entry_text(t, args.title or "Need %s opened" % nid, args.body or "%s Default if no answer: %s" % (
                records.sentence(args.text), default))
        if kind == "need-resolved":
            _need(args, "id", "answer")
            rows = [n for n in wl["needs"] if n["id"] == args.id]
            if not rows:
                raise WorklogError("unknown need %s; open needs: %s" % (args.id, ", ".join(
                    n["id"] for n in wl["needs"] if n.get("answer") is None) or "none"))
            if rows[0].get("answer") is not None:
                raise WorklogError("need %s is already answered (%s)" % (args.id, _when(rows[0]["answered_at"])))
            rows[0]["answer"] = records.sentence(args.answer)
            rows[0]["answered_at"] = paths.iso(t)
            ctx.messages.append("resolved need %s" % args.id)
            return entry_text(t, args.title or "Need %s answered" % args.id, args.body or records.sentence(args.answer))
        if kind == "incident":
            _need(args, "what", "effect", "fix")
            pid = _next_id(wl["incidents"], "P")
            wl["incidents"].append({"id": pid, "at": paths.iso(t), "what": records.sentence(args.what),
                                    "effect": args.effect.strip(), "fix": args.fix.strip()})
            ctx.messages.append("recorded incident %s" % pid)
            return entry_text(t, args.title or "Process incident %s" % pid, args.body or "%s Effect: %s Fix: %s" % (
                records.sentence(args.what), records.sentence(args.effect), records.sentence(args.fix)))
        if kind == "checkpoint":
            return checkpoint_block(ctx, args, cfg, session)
        if kind == "compaction":
            title = args.title or _compaction_title(ctx.st)
        else:
            _need(args, "title")
            title = args.title
        prefix = TITLE_PREFIX.get(kind)
        if prefix and not title.lower().startswith(prefix.strip().lower()):
            title = prefix + title
        return entry_text(t, title, args.body)

    return mutate


