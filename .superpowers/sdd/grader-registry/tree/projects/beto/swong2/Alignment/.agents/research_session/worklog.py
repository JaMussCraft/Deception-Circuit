# The one write path


class Ctx(object):
    def __init__(self, d, wl, st, ledger, t):
        self.dir, self.wl, self.st, self.ledger, self.t = d, wl, st, ledger, t
        self.ledger_changed = False
        self.messages = []


def update_direction(cfg, d, mutate=None, t=None, require_worklog=True, worklog=None, create_ledger=None):
    """Lock, load, ``entry = mutate(ctx)``, re-render the head, lint, write, and stamp ``last_worklog_entry_at``.

    Returns ``(ctx, warnings)``. ``mutate`` may change ``ctx.wl`` and ``ctx.ledger`` (set ``ctx.ledger_changed``) and
    returns the Log entry text or None.
    """
    t = records.now() if t is None else t
    d = os.path.abspath(d)
    if not os.path.isdir(d):
        raise WorklogError("no direction directory at %s" % d)
    with records.records_lock(cfg, d):
        wl = worklog if worklog is not None else _load(os.path.join(d, "worklog.json"))
        if wl is None:
            raise WorklogError("no worklog.json in %s; create the direction with `research-session init` or import "
                               "a hand-written WORKLOG.md with `worklog-append %s --import`" % (d, d))
        ledger = create_ledger if create_ledger is not None else _load(os.path.join(d, "ledger.json"))
        st = _load(os.path.join(d, "state.json"))
        ctx = Ctx(d, wl, st, ledger, t)
        entry = mutate(ctx) if mutate else None
        ctx.wl["budgets"] = budgets(ctx.ledger)
        errors, _ = registry.validate_worklog(ctx.wl)
        if errors:
            raise UsageError("worklog.json would be invalid: " + "; ".join(errors[:5]))
        if ctx.ledger_changed or create_ledger is not None:
            registry.carry_legacy(ctx.ledger)
            ctx.ledger["totals"] = registry.ledger_totals(ctx.ledger)
            errors, _ = registry.validate_ledger(ctx.ledger)
            if errors:
                raise UsageError("ledger.json would be invalid: " + "; ".join(errors[:5]))
        md_path = os.path.join(d, "WORKLOG.md")
        old_text = records.read_text(md_path) if os.path.exists(md_path) else ""
        _, log_body = split_log(old_text)
        if log_body is None:
            if old_text.strip():
                raise WorklogError("%s has no \"## Log\" heading; import or repair it first" % md_path)
            log_body = ""
        if entry:
            log_body = append_entry(log_body, entry, t)
        new_text = render_head(ctx.wl, ctx.st, ctx.ledger, log_body, t) + LOG_MARK + log_body
        warnings = lint_gate(old_text, new_text)
        if ctx.ledger_changed or create_ledger is not None:
            records.write_json(os.path.join(d, "ledger.json"), ctx.ledger)
        records.write_json(os.path.join(d, "worklog.json"), ctx.wl)
        if new_text != old_text:
            records.write_text_atomic(md_path, new_text)
        if entry:
            stamp_last_entry(cfg, d, t, warnings)
    return ctx, warnings


def stamp_last_entry(cfg, d, t, warnings):
    sp = records.state_json_path(d)
    if not os.path.exists(sp):
        warnings.append("no state.json in %s; last_worklog_entry_at not recorded (run `init --missing-only`)" % d)
        return
    with records.state_lock(cfg, sp):
        st = _load(sp)
        st["last_worklog_entry_at"] = paths.iso(t)
        records.write_json(sp, st)


