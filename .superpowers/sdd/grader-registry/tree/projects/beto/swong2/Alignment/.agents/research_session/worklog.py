# The checkpoint block (lane 4 section 1; spec 5.2, 5.4)


def _concurrent(cfg, tag):
    rows = state.load_directions(cfg) or []
    others = sorted(set(r.get("claimed_by") for r in rows if r.get("claimed_by") and r.get("claimed_by") != tag
                        and r.get("status") in ("claimed", "active")))
    return ", ".join(others) if others else "none"


def checkpoint_block(ctx, args, cfg, session):
    _need(args, "checkpoint", "body", "plan")
    n = args.checkpoint
    cp = [c for c in session.get("checkpoints") or [] if c.get("n") == n]
    cp = cp[0]
    u = session.get("usage") or {}
    pts = (cp.get("session_points") or 0) - (u.get("points_at_register") or 0)
    allm, fable = cp.get("all_models"), cp.get("fable")
    head = "CHECKPOINT %d (+%s session points; all models %s, Fable %s; resets %s)" % (
        n, _num(pts), _pct(allm), _pct(fable), _reset_text(u))
    prev = [c for c in session.get("checkpoints") or [] if c.get("n") == n - 1]
    since = paths.parse_iso(prev[0].get("at")) if prev else None
    incs = [p["id"] for p in ctx.wl["incidents"] if since is None or (paths.parse_iso(p.get("at")) or 0) > since]
    gap = None if (allm is None or fable is None) else fable - allm
    if gap is not None and gap > FABLE_GAP:
        gap_text = "Fable is %s points above all models: delegate reading, analysis and review to Opus agents" % _num(
            gap)
    else:
        gap_text = "within %d points" % FABLE_GAP if gap is not None else "unknown"
    running = args.running
    if not running:
        jobs = [j for j in (ctx.st or {}).get("jobs") or [] if j.get("status") not in TERMINAL_JOB]
        running = ", ".join("job %s on %s" % (j["job_id"], j.get("cluster")) for j in jobs) or "nothing recorded"
    b = budgets(ctx.ledger)
    lines = [
        "**%s · %s.**" % (records.clock_text(records.local(ctx.t)), head),
        "- Since the last checkpoint: %s" % records.sentence(args.body),
        "- Spend: GPU %s; OpenRouter %s; compactions %d." % (b["gpu"], b["openrouter"], int(session.get(
            "compactions") or 0)),
        "- Process health: %s" % records.sentence(", ".join(incs) if incs else "no incidents"),
        "- Fable gap: %s" % records.sentence(gap_text),
        "- Concurrent sessions sharing the usage meter: %s" % records.sentence(
            args.concurrent or _concurrent(cfg, session.get("tag"))),
        "- Plan to the next checkpoint: %s" % records.sentence(args.plan),
        "- Frozen until you reply \"continue\": new agents, new Slurm jobs and messages to workers other than HOLD. "
        "Still running and not cancelled: %s" % records.sentence(running),
    ]
    return "\n".join(lines)


