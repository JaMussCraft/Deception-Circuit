def _report(warnings):
    for w in warnings:
        sys.stderr.write("research-session: warning: %s\n" % w)


def cmd_worklog_append(args):
    cfg = paths.Config.from_env()
    try:
        if args.import_:
            data, diff, warnings = import_worklog(cfg, args.dir)
            _report(warnings)
            print("imported %s: %d findings, %d needs, %d incidents; the Log is unchanged" % (
                os.path.join(os.path.abspath(args.dir), "worklog.json"), len(data["findings"]), len(data["needs"]),
                len(data["incidents"])))
            print(diff or "head unchanged")
            return 0
        if not args.kind:
            raise UsageError("--kind is required (or --import)")
        session = None
        if args.kind == "checkpoint":
            _need(args, "checkpoint", "body", "plan")
            try:
                session = state.find_session(cfg, args.session, os.path.realpath(args.cwd or os.getcwd()))
            except state.StateError as exc:
                raise WorklogError(str(exc))
            if not [c for c in session.get("checkpoints") or [] if c.get("n") == args.checkpoint]:
                raise WorklogError("checkpoint %d has not crossed for session %s; crossed: %s" % (
                    args.checkpoint, session.get("tag"),
                    ", ".join(str(c.get("n")) for c in session.get("checkpoints") or []) or "none"))
        ctx, warnings = update_direction(cfg, args.dir, make_mutator(args, cfg, session))
        if session is not None:
            n = args.checkpoint
            now = ctx.t
            s, ok, mirrored = state.update_session(
                cfg, session["tool"], session["session_id"],
                lambda rec: state.mark_checkpoint_recorded(rec, n, now), now, create=False)
            if ok:
                ctx.messages.append("freeze for checkpoint %d is now recorded (state.json %s)" % (n, mirrored))
            else:
                warnings.append("no crossed freeze for checkpoint %d; the freeze state is unchanged" % n)
    except UsageError as exc:
        sys.stderr.write("research-session: %s\n" % exc)
        return 2
    except WorklogError as exc:
        sys.stderr.write("research-session: %s\n" % exc)
        return 1
    _report(warnings)
    print("%s: %s" % (os.path.join(os.path.abspath(args.dir), "WORKLOG.md"),
                      "; ".join(ctx.messages) if ctx.messages else "entry appended"))
    return 0


def cmd_worklog_set(args):
    cfg = paths.Config.from_env()
    try:
        ctx, warnings = set_field(cfg, args.dir, args.field, args.value)
    except UsageError as exc:
        sys.stderr.write("research-session: %s\n" % exc)
        return 2
    except WorklogError as exc:
        sys.stderr.write("research-session: %s\n" % exc)
        return 1
    _report(warnings)
    print("%s set; WORKLOG.md head re-rendered" % args.field)
    return 0


