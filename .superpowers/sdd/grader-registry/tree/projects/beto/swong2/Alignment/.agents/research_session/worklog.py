# The Log


ENTRY_RE = re.compile(r"^\*\*([0-9]{1,2}:[0-9]{2} [ap]m [A-Z]{2,5}) · ")
DAY_RE = re.compile(r"^### ([A-Z][a-z]+) ([0-9]{1,2}) ([A-Z][a-z]+) ([0-9]{4})\s*$")


def log_days(log_body):
    """``[(date, [entry clock texts])]`` in file order."""
    import datetime
    out = []
    for line in (log_body or "").splitlines():
        m = DAY_RE.match(line)
        if m and m.group(3) in records.MONTHS:
            out.append((datetime.date(int(m.group(4)), records.MONTHS.index(m.group(3)) + 1, int(m.group(2))), []))
            continue
        e = ENTRY_RE.match(line)
        if e and out:
            out[-1][1].append(e.group(1))
    return out


def started_text(log_body, t):
    for day, entries in log_days(log_body):
        if entries:
            return "%s %d %s %d, %s" % (records.WEEKDAYS[day.weekday()][:3], day.day, records.MONTHS[day.month - 1][:3],
                                        day.year, entries[0])
    return records.long_when(records.local(t))


def append_entry(log_body, entry, t):
    """Add ``entry`` (one or more lines) at the end, with a day heading when the day changed."""
    dt = records.local(t)
    heading = records.day_heading(dt)
    out = log_body or ""
    last = None
    for line in out.splitlines():
        if line.startswith("### "):
            last = line.rstrip()
    if out and not out.endswith("\n"):
        out += "\n"
    if last != heading:
        if out and not out.endswith("\n\n"):
            out += "\n"
        out += heading + "\n"
    return out + entry.rstrip("\n") + "\n"


def entry_text(t, title, body=None):
    head = "**%s · %s**" % (records.clock_text(records.local(t)), records.sentence(title))
    body = (body or "").strip()
    return head + (" " + body if body else "")


# ---------------------------------------------------------------------------------------------------------------
# The head


def need_line(n):
    when = _when(n.get("at"))
    if n.get("answer") is not None:
        return "- ~~%s (%s): %s~~ Answered %s: %s" % (n["id"], when, n["text"], _when(n.get("answered_at")),
                                                     n["answer"])
    line = "- %s (%s): %s" % (n["id"], when, n["text"])
    if n.get("default"):
        line += " Default if no answer: %s" % DEFAULT_PREFIX_RE.sub("", n["default"])
    return line


def render_head(wl, st, ledger, log_body, t):
    """Everything above ``## Log``, in the ``_templates/WORKLOG.md`` layout."""
    b = budgets(ledger)
    allm, fable, cps = usage_rows(st)
    open_needs = len([n for n in wl.get("needs") or [] if n.get("answer") is None])
    dirs = " · ".join("%d. %s: %s" % (i + 1, d["name"], d["state"]) for i, d in enumerate(wl.get("directions") or []))
    values = (
        state_row(wl, st),
        dirs or "none recorded yet",
        "%s / %s" % (started_text(log_body, t), records.long_when(records.local(t))),
        "%d, counted by the compaction hook" % compactions(st),
        allm, fable, cps,
        gpu_row(ledger, b),
        b["openrouter"],
        "%d, see below" % open_needs if open_needs else "0",
        wl.get("transcripts") or "not recorded yet",
    )
    lines = ["# Worklog: %s" % wl["title"], "", GENERATED, "| | |", "|---|---|"]
    lines += ["| %s | %s |" % (label, _cell(v)) for label, v in zip(HEAD_ROWS, values)]
    terms = " ".join("*%s*: %s" % (x["term"], records.sentence(x["meaning"])) for x in wl.get("terms") or [])
    lines += ["", "**Right now.** %s" % wl["right_now"], "", "**Terms.** %s" % (terms or "None yet."), "",
              "## Needs from you"]
    needs = [need_line(n) for n in wl.get("needs") or []]
    lines += needs or ["None so far."]
    lines += ["", "## Findings register", FINDINGS_HEADER]
    lines += ["| %s | %s | %s | %s | %s | %s |" % (f["id"], _when(f["at"]), _cell(f["plain"]), _cell(f["setup"]),
                                                   f["strength"], _cell(f["evidence"])) for f in wl.get("findings") or []]
    lines += ["", STRENGTH_NOTE, "", "## Process incidents", INCIDENTS_HEADER]
    lines += ["| %s | %s | %s | %s | %s |" % (p["id"], _when(p["at"]), _cell(p["what"]), _cell(p["effect"]),
                                              _cell(p["fix"])) for p in wl.get("incidents") or []]
    return "\n".join(lines) + "\n\n"


# ---------------------------------------------------------------------------------------------------------------
# Lint gate


def _lint_keys(text):
    return set((f.rule, f.excerpt) for f in _lint.lint_text(text))


def lint_gate(old_text, new_text, name="WORKLOG.md"):
    """Raise WorklogError on lint failures the write introduces; return warnings for failures already present."""
    old = _lint_keys(old_text or "")
    introduced, kept = [], []
    for f in _lint.lint_text(new_text):
        (kept if (f.rule, f.excerpt) in old else introduced).append(_lint.format_finding(name, f))
    if introduced:
        raise WorklogError("refused by the lint; nothing was written. Rewrite the text in full sentences with normal "
                           "spacing:\n" + "\n".join(introduced))
    return ["pre-existing lint failure kept: " + k for k in kept]


def lint_value(value, what):
    found = _lint.lint_text(value)
    if found:
        raise WorklogError("refused by the lint; nothing was written. %s fails:\n%s" % (
            what, "\n".join(_lint.format_finding(what, f) for f in found)))


