"""The structured worklog writer (spec 4.8, 5.6; R22, R33, R39).

``WORKLOG.md`` has a head and a Log. Everything above ``## Log`` is regenerated by ``render_head`` from
``worklog.json``, ``state.json`` and ``ledger.json`` on every RS write, row for row as in ``_templates/WORKLOG.md``.
The Log is append-only: a write keeps every byte after ``## Log`` and adds at most one entry at the end.

``update_direction`` is the one write path. ``worklog-append``, ``worklog-set``, ``ledger`` and ``init`` all call it,
so the head always matches the records. It holds the direction's records lock, lints the whole new file, refuses
lint failures the write would introduce (failures already in the file are reported as warnings), and replaces the
files atomically.
"""

import argparse
import difflib
import json
import os
import re
import sys

from research_session import lint as _lint
from research_session import paths, records, registry, state

HEAD_ROWS = ("State", "Directions", "Started / last updated", "Orchestrator auto-compactions",
             "Weekly usage, all models", "Weekly usage, Fable", "Review checkpoints", "GPU budget",
             "OpenRouter credit", "Open needs from you", "Transcripts (for audits)")
KINDS = ("entry", "checkpoint", "handback", "job", "compaction", "decision", "incident", "switch", "finding", "need",
         "need-resolved")
TITLE_PREFIX = {"handback": "Hand-back: "}
TERMINAL_JOB = ("COMPLETED", "FAILED", "CANCELLED", "TIMEOUT", "OUT_OF_MEMORY", "NODE_FAIL", "PREEMPTED")
CAP_PERCENT = 80
FABLE_GAP = 5
LOG_MARK = "## Log\n"
GENERATED = ("<!-- Generated by research-session from worklog.json, state.json and ledger.json. Everything above "
             "\"## Log\" is rewritten on every write; never edit it by hand. The Log below is append-only. -->")
FINDINGS_HEADER = ("| # | When | Finding, in plain words | Setup needed to read it | Strength | Evidence |\n"
                   "|---|---|---|---|---|---|")
STRENGTH_NOTE = "Strength is one of: preliminary, reviewed by an independent agent, or final."
INCIDENTS_HEADER = ("| # | When | What went wrong (agent workflow) | Effect | Fix or status |\n"
                    "|---|---|---|---|---|")
SHORT_RE = r"[A-Z][a-z]{2} [0-9]{1,2}:[0-9]{2} [ap]m"
DEFAULT_PREFIX_RE = re.compile(r"^(default )?if no answer:\s*", re.I)


class WorklogError(Exception):
    """A refusal: exit 1."""


class UsageError(Exception):
    """Bad arguments or values: exit 2."""


# ---------------------------------------------------------------------------------------------------------------
# Loading


def _load(path):
    try:
        return state.load_json(path)
    except ValueError as exc:
        raise WorklogError("%s is not valid JSON: %s" % (path, exc))


def split_log(text):
    """``(head, log_body)``. ``log_body`` is every byte after the ``## Log`` line; None when there is no Log."""
    if text.startswith(LOG_MARK):
        return "", text[len(LOG_MARK):]
    i = text.find("\n" + LOG_MARK)
    if i < 0:
        return text, None
    return text[:i + 1], text[i + 1 + len(LOG_MARK):]


# ---------------------------------------------------------------------------------------------------------------
# Small formatters


def _num(x):
    x = float(x or 0)
    return str(int(x)) if x.is_integer() else ("%.2f" % x).rstrip("0").rstrip(".")


def _pct(x):
    return "unknown" if x is None else _num(x) + "%"


def _money(x):
    return "$%.2f" % float(x or 0)


def _cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def _when(value):
    """Register form ``Sat 9:20 am`` from an ISO time; an imported value that was not resolvable stays as written."""
    dt = records.from_iso(value)
    return records.short_when(dt) if dt else (value or "")


def _lower_first(s):
    return s[:1].lower() + s[1:] if s else s


CLUSTER_NAMES = {"delta": "Delta", "bridges2": "Bridges-2", "bridges-2": "Bridges-2"}


# ---------------------------------------------------------------------------------------------------------------
# Budgets (from ledger.json)


def budgets(ledger):
    if not isinstance(ledger, dict):
        return {"gpu": "no ledger.json yet", "openrouter": "no ledger.json yet"}
    caps, tot = ledger.get("caps") or {}, ledger.get("totals") or {}
    gpu = "%.1f of %s GPU-h actual (%.1f reserved)" % (float(tot.get("actual_gpu_seconds") or 0) / 3600.0,
                                                       _num(caps.get("reserved_gpu_hours")),
                                                       float(tot.get("reserved_gpu_hours") or 0))
    api = "%s of %s cap" % (_money(tot.get("api_usd_known")), _money(caps.get("paid_api_usd")))
    if float(tot.get("api_usd_reserve") or 0) > 0:
        api += ", plus %s reserved" % _money(tot.get("api_usd_reserve"))
    return {"gpu": gpu, "openrouter": api}


def gpu_row(ledger, b):
    if not isinstance(ledger, dict):
        return b["gpu"]
    k = int((ledger.get("caps") or {}).get("max_concurrent_gpu_jobs") or 0)
    jobs = "no GPU jobs allowed" if k == 0 else "at most %d job%s at once" % (k, "" if k == 1 else "s")
    names = []
    for r in ledger.get("reservations") or []:
        n = CLUSTER_NAMES.get(str(r.get("cluster")).lower(), r.get("cluster"))
        if n and n not in names:
            names.append(n)
    return "%s; %s; clusters: %s" % (b["gpu"], jobs, ", ".join(names) if names else "none yet")


