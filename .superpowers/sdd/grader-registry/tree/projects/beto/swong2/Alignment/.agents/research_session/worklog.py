def _short_to_iso(text, days):
    """Resolve ``Sat 9:20 am`` to an ISO time when exactly one Log day has that weekday; else keep the text."""
    import datetime
    m = re.match(r"^([A-Z][a-z]{2}) ([0-9]{1,2}):([0-9]{2}) ([ap]m)$", (text or "").strip())
    if not m:
        return text
    cands = sorted(set(d for d, _ in days if records.WEEKDAYS[d.weekday()][:3] == m.group(1)))
    if len(cands) != 1:
        return text
    hour = int(m.group(2)) % 12 + (12 if m.group(4) == "pm" else 0)
    dt = datetime.datetime(cands[0].year, cands[0].month, cands[0].day, hour, int(m.group(3)), tzinfo=records.zone())
    return paths.iso(dt.timestamp())


def _section(lines, title):
    out, on = [], False
    for line in lines:
        if line.startswith("## "):
            on = line.strip() == "## " + title
            continue
        if on:
            out.append(line)
    return out


def _paragraph(lines, label):
    for i, line in enumerate(lines):
        if line.startswith("**%s.** " % label):
            out = [line[len("**%s.** " % label):]]
            for nxt in lines[i + 1:]:
                if not nxt.strip() or nxt.startswith("#") or nxt.startswith("**"):
                    break
                out.append(nxt)
            return "\n".join(out)
    return None


def parse_head(head, log_body):
    """Parse a lane 4 style head (hand-written or rendered). Returns ``(data, problems)``."""
    days = log_days(log_body)
    lines = head.splitlines()
    problems = []
    title = None
    for line in lines:
        if line.startswith("# "):
            title = re.sub(r"^# (Worklog: )?", "", line).strip()
            break
    rows = {}
    for line in lines:
        if line.startswith("## "):
            break
        if line.startswith("| ") and not line.startswith("| |"):
            cells = registry.split_row(line)
            if len(cells) == 2:
                rows[cells[0]] = cells[1]
    state_value = rows.get("State", "Running")
    base = "Running"
    if state_value.lower().startswith("blocked"):
        base = "Blocked: needs you"
    elif state_value.lower().startswith("closed"):
        base = "Closed"
    directions = []
    for part in [p for p in re.split(r" · ", rows.get("Directions", "")) if p.strip()]:
        m = re.match(r"^\s*[0-9]+\. (.*?): (.*)$", part)
        if m:
            directions.append({"name": m.group(1).strip(), "state": m.group(2).strip()})
        elif part.strip() != "none recorded yet":
            problems.append("directions entry not parsed: %r" % part)
    terms = []
    terms_text = _paragraph(lines, "Terms") or ""
    for m in re.finditer(r"\*([^*]+)\*: (.*?)(?=\s\*[^*]+\*: |\s*$)", terms_text, re.S):
        terms.append({"term": m.group(1).strip(), "meaning": m.group(2).strip()})
    needs, findings, incidents = [], [], []
    for line in _section(lines, "Needs from you"):
        if not line.strip() or line.strip() == "None so far.":
            continue
        m = re.match(r"^- ~~(N[0-9]+) \((.*?)\): (.*)~~ Answered (" + SHORT_RE + r"): (.*)$", line)
        if m:
            needs.append({"id": m.group(1), "at": _short_to_iso(m.group(2), days), "text": m.group(3),
                          "default": None, "answer": m.group(5), "answered_at": _short_to_iso(m.group(4), days)})
            continue
        m = re.match(r"^- (N[0-9]+) \((.*?)\): (.*?)(?: Default if no answer: (.*))?$", line)
        if m:
            needs.append({"id": m.group(1), "at": _short_to_iso(m.group(2), days), "text": m.group(3),
                          "default": m.group(4), "answer": None, "answered_at": None})
            continue
        problems.append("needs line not parsed: %s" % line)
    for name, out, width, keys in (("Findings register", findings, 6, ("plain", "setup", "strength", "evidence")),
                                   ("Process incidents", incidents, 5, ("what", "effect", "fix"))):
        for line in _section(lines, name):
            if not line.startswith("|"):
                continue
            cells = registry.split_row(line)
            if cells and cells[0] in ("#",) or all(re.match(r"^:?-+:?$", c) for c in cells if c):
                continue
            if len(cells) != width or not re.match(r"^[FP][0-9]+$", cells[0]):
                problems.append("%s row not parsed: %s" % (name.lower(), line))
                continue
            rec = {"id": cells[0], "at": _short_to_iso(cells[1], days)}
            rec.update(zip(keys, cells[2:]))
            out.append(rec)
    data = {"schema": 1, "title": title or "Untitled session", "state": base,
            "right_now": _paragraph(lines, "Right now") or "Not recorded.", "directions": directions, "terms": terms,
            "budgets": {"gpu": "", "openrouter": ""}, "transcripts": rows.get("Transcripts (for audits)") or
            "not recorded yet", "needs": needs, "findings": findings, "incidents": incidents}
    return data, problems


def _register_view(data):
    return {"needs": [need_line(n) for n in data["needs"]],
            "findings": [(f["id"], _when(f["at"]), f["plain"], f["setup"], f["strength"], f["evidence"])
                         for f in data["findings"]],
            "incidents": [(p["id"], _when(p["at"]), p["what"], p["effect"], p["fix"]) for p in data["incidents"]]}


def import_worklog(cfg, d, t=None):
    """Build ``worklog.json`` from a hand-written ``WORKLOG.md``; re-render the head; return the head diff."""
    t = records.now() if t is None else t
    d = os.path.abspath(d)
    md_path, wl_path = os.path.join(d, "WORKLOG.md"), os.path.join(d, "worklog.json")
    with records.records_lock(cfg, d):
        if os.path.exists(wl_path):
            raise WorklogError("%s already exists; RS already owns this worklog, so there is nothing to import"
                               % wl_path)
        if not os.path.exists(md_path):
            raise WorklogError("no WORKLOG.md in %s" % d)
        old = records.read_text(md_path)
        old_head, log_body = split_log(old)
        if log_body is None:
            raise WorklogError("%s has no \"## Log\" heading" % md_path)
        data, problems = parse_head(old_head, log_body)
        if problems:
            raise WorklogError("refused; these head rows would be lost:\n" + "\n".join(problems))
        errors, _ = registry.validate_worklog(dict(data, budgets={"gpu": "", "openrouter": ""}))
        if errors:
            raise WorklogError("refused; the imported worklog.json would be invalid: " + "; ".join(errors[:5]))
        st = _load(os.path.join(d, "state.json"))
        ledger = _load(os.path.join(d, "ledger.json"))
        data["budgets"] = budgets(ledger)
        new_head = render_head(data, st, ledger, log_body, t)
        new = new_head + LOG_MARK + log_body
        if split_log(new)[1].encode() != log_body.encode():
            raise WorklogError("refused; the Log would change")
        again, problems = parse_head(new_head, log_body)
        lost = []
        before, after = _register_view(data), _register_view(again)
        for k in ("needs", "findings", "incidents"):
            for row in before[k]:
                if row not in after[k]:
                    lost.append("%s: %s" % (k, row if isinstance(row, str) else row[0]))
        if lost or problems:
            raise WorklogError("refused; rows would be lost: " + "; ".join(lost + problems))
        warnings = lint_gate(old, new)
        records.write_json(wl_path, data)
        if new != old:
            records.write_text_atomic(md_path, new)
    diff = "".join(difflib.unified_diff(old_head.splitlines(True), new_head.splitlines(True), "old head", "new head"))
    return data, diff, warnings


