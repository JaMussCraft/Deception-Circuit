TEXT_FIELDS = {"title": "title", "state": "state", "right-now": "right_now", "transcripts": "transcripts"}
LIST_FIELDS = {"directions": registry.check_directions_list, "terms": registry.check_terms_list}
CAP_FIELDS = {"gpu-cap": ("reserved_gpu_hours", float), "max-gpu-jobs": ("max_concurrent_gpu_jobs", int),
              "api-cap": ("paid_api_usd", float)}
SET_FIELDS = tuple(TEXT_FIELDS) + tuple(LIST_FIELDS) + tuple(CAP_FIELDS)


def set_field(cfg, d, field, raw):
    if field in TEXT_FIELDS:
        value = raw.strip()
        if not value:
            raise UsageError("%s cannot be empty" % field)
        if field == "state" and value not in registry.WORKLOG_STATE:
            raise UsageError("state must be one of: %s. A freeze or cap pause is shown over it automatically."
                             % "; ".join(registry.WORKLOG_STATE))
        if field == "right-now" and len(value.splitlines()) > 3:
            raise UsageError("right-now is three lines at most")
        lint_value(value, field)

        def mutate(ctx):
            ctx.wl[TEXT_FIELDS[field]] = value
        return update_direction(cfg, d, mutate)
    if field in LIST_FIELDS:
        try:
            value = json.loads(raw)
        except ValueError as exc:
            raise UsageError("%s takes a JSON list: %s" % (field, exc))
        errors = LIST_FIELDS[field](value)
        if errors:
            raise UsageError("; ".join(errors[:5]))
        for item in value:
            for v in item.values():
                lint_value(v, field)

        def mutate(ctx):
            ctx.wl[field] = value
        return update_direction(cfg, d, mutate)
    key, cast = CAP_FIELDS[field]
    try:
        value = cast(raw)
    except ValueError:
        raise UsageError("%s takes a %s" % (field, "whole number" if cast is int else "number"))
    if value < 0:
        raise UsageError("%s cannot be negative" % field)

    def mutate(ctx):
        if not isinstance(ctx.ledger, dict):
            raise WorklogError("no ledger.json in %s; create it with `research-session init %s --missing-only`" % (
                ctx.dir, os.path.basename(ctx.dir)))
        ctx.ledger["caps"][key] = value
        ctx.ledger_changed = True
    return update_direction(cfg, d, mutate)


