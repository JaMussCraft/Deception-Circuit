# Sessions (from state.json)


def current_session(st):
    """The mirrored session record read most recently, or None."""
    sessions = (st or {}).get("sessions") or {}
    best, key = None, None
    for tag, rec in sessions.items():
        if not isinstance(rec, dict):
            continue
        last = ((rec.get("usage") or {}).get("last_reading") or {}).get("read_at")
        k = (paths.parse_iso(last) or 0, paths.parse_iso(rec.get("started_at")) or 0, tag)
        if key is None or k > key:
            best, key = rec, k
    return best


def _reset_text(u):
    segs = (u or {}).get("segments") or []
    if segs and segs[-1].get("resets_at"):
        try:
            return records.reset_when(float(segs[-1]["resets_at"]))
        except (TypeError, ValueError):
            pass
    return "the weekly reset"


def state_row(wl, st):
    rec = current_session(st)
    parts = []
    if rec:
        u = rec.get("usage") or {}
        last = u.get("last_reading") or {}
        weekly = [v for v in (last.get("seven_day"), last.get("fable")) if v is not None]
        five = last.get("five_hour")
        if (weekly and max(weekly) >= CAP_PERCENT) or (five is not None and five >= CAP_PERCENT):
            parts.append("Paused for usage cap until %s" % _reset_text(u))
        freeze = u.get("freeze") or {}
        if freeze.get("checkpoint", 0) > u.get("acked_through", 0):
            parts.append("At checkpoint %d, frozen until you reply \"continue\"" % freeze["checkpoint"])
    if not parts:
        return wl["state"]
    return "; ".join([parts[0]] + [_lower_first(p) for p in parts[1:]])


def usage_rows(st):
    rec = current_session(st)
    if not rec or not (rec.get("usage") or {}).get("last_reading"):
        none = "no reading yet; no session has registered" if not rec else "no reading yet"
        cps = "none yet; checkpoints start when the session registers" if not rec else None
        if rec:
            u = rec.get("usage") or {}
            cps = "none yet; first at +%s session points; cadence %s points; cap pause at %d%%" % (
                _num((u.get("next_checkpoint") or 1) * (u.get("cadence") or 0)), _num(u.get("cadence")), CAP_PERCENT)
        return none, none, cps
    u = rec["usage"]
    last = u["last_reading"]
    since = (u.get("session_points") or 0) - (u.get("points_at_register") or 0)
    allm = "account reads %s; +%s points this session" % (_pct(last.get("seven_day")), _num(since))
    fable, seven = last.get("fable"), last.get("seven_day")
    if fable is None:
        frow = "no Fable reading"
    elif seven is not None and fable - seven > FABLE_GAP:
        frow = "account reads %s; %s points above all models, so reading, analysis and review go to Opus agents" % (
            _pct(fable), _num(fable - seven))
    else:
        frow = "account reads %s; within %d points of all models" % (_pct(fable), FABLE_GAP)
    cps = rec.get("checkpoints") or []
    acked = len([c for c in cps if c.get("acked_at")])
    nxt = "next at +%s session points" % _num((u.get("next_checkpoint") or 1) * (u.get("cadence") or 0))
    if cps:
        crow = "%d of %d acknowledged; %s" % (acked, len(cps), nxt)
    else:
        crow = "none yet; first at +%s session points" % _num((u.get("next_checkpoint") or 1) * (u.get("cadence") or 0))
    crow += "; cadence %s points; cap pause at %d%%" % (_num(u.get("cadence")), CAP_PERCENT)
    return allm, frow, crow


def compactions(st):
    return sum(int((rec or {}).get("compactions") or 0) for rec in ((st or {}).get("sessions") or {}).values())


